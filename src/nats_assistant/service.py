from importlib.resources import files
import os
from pathlib import Path
import shutil
import subprocess
import sys

from nats_assistant.config import get_config_path, write_private_file

UNIT_NAME = "nats-assistant.service"
GENERATED_MARKER = "# Generated by nats-assistant service install."
SERVICE_ACTIONS = frozenset({"install", "uninstall", "status", "start", "stop", "restart", "enable", "disable"})


class ServiceError(ValueError):
    """Controlled service setup failures."""


def resolve_executable() -> Path:
    adjacent = Path(sys.executable).absolute().parent / "nats-assistant"
    invoked = Path(sys.argv[0]).expanduser()
    candidates = [adjacent]
    if invoked.name == "nats-assistant":
        candidates.append(invoked)
    found = shutil.which("nats-assistant")
    if found:
        candidates.append(Path(found))
    for candidate in candidates:
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return candidate.resolve()
    raise ServiceError("Cannot find the installed nats-assistant executable; install the package first")


def _unit_quote(value: str) -> str:
    if any(ord(character) < 32 or ord(character) == 127 for character in value):
        raise ServiceError("Service paths cannot contain control characters")
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    # The executable position and Environment= do not expand $variables.
    return f'"{escaped}"'


def render_service(executable: Path, config_path: Path) -> str:
    if not executable.is_absolute() or not config_path.is_absolute():
        raise ServiceError("Service paths must be absolute")
    if any(character in str(executable) for character in ('"', "'", "\\")):
        raise ServiceError("The executable path contains characters unsupported by systemd; use another install location")
    template = files("nats_assistant").joinpath("nats-assistant.service.in").read_text(encoding="utf-8")
    return template.replace("@EXECUTABLE@", _unit_quote(str(executable))).replace(
        "@CONFIG_ENVIRONMENT@", _unit_quote(f"NATS_CONFIG_FILE={config_path}")
    )


def service_path() -> Path:
    root = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    return root.expanduser().absolute() / "systemd" / "user" / UNIT_NAME


def _systemctl(*arguments: str) -> int:
    try:
        return subprocess.run(["systemctl", "--user", *arguments], check=False, timeout=30).returncode
    except (OSError, subprocess.TimeoutExpired):
        raise ServiceError("Unable to run systemctl --user; check that the user service manager is available") from None


def _check_owned_unit(path: Path) -> None:
    if path.exists() and (path.is_symlink() or not path.read_text(encoding="utf-8").startswith(GENERATED_MARKER)):
        raise ServiceError("An unmanaged nats-assistant user unit already exists; review it before replacing it")


def manage_service(action: str) -> int:
    if action not in SERVICE_ACTIONS:
        raise ServiceError("Unsupported service action")
    if action == "install":
        path = service_path()
        _check_owned_unit(path)
        write_private_file(path, render_service(resolve_executable(), get_config_path()))
        result = _systemctl("daemon-reload")
        if result == 0:
            print(f"Installed {path}. Run service enable and service start to enable login startup and start NATS.")
        return result
    if action == "uninstall":
        path = service_path()
        if not path.exists():
            raise ServiceError("No generated NATS user service is installed")
        _check_owned_unit(path)
        result = _systemctl("disable", "--now", UNIT_NAME)
        if result != 0:
            return result
        path.unlink()
        return _systemctl("daemon-reload")
    return _systemctl(action, UNIT_NAME)
